import { mkdir, readFile, writeFile } from "node:fs/promises";
import { bucket } from "../src/icons/bucket.js";

const collection = JSON.parse(
  await readFile(
    new URL("../node_modules/@iconify-json/lucide/icons.json", import.meta.url),
    "utf8",
  ),
);
const names = [
  ...Object.keys(collection.icons),
  ...Object.keys(collection.aliases ?? {}),
].sort();
const icons = {};
const groups = Array.from({ length: 32 }, () => ({}));
for (const name of names) {
  let parent = name;
  while (collection.aliases?.[parent])
    parent = collection.aliases[parent].parent;
  const {
    body,
    width = collection.width,
    height = collection.height,
  } = collection.icons[parent];
  const data = {
    body,
    ...(width !== 24 && { width }),
    ...(height !== 24 && { height }),
  };
  const group = groups[bucket(name)];
  icons[parent] = group[parent] = data;
  icons[name] = group[name] = name === parent ? data : parent;
}

const entries = new URL("../.cache/icons/", import.meta.url);
await mkdir(entries, { recursive: true });
for (const name of names) {
  const value = icons[name];
  const data =
    typeof value === "string"
      ? { [value]: icons[value], [name]: value }
      : { [name]: value };
  await writeFile(
    new URL(`${name}.js`, entries),
    `import { install } from "../../src/icons/store";\ninstall(${JSON.stringify(data)}, true);\n`,
  );
}

const directory = new URL("../src/icons/data/", import.meta.url);
await mkdir(directory, { recursive: true });
for (const [name, data] of [...groups.entries(), ["all", icons]]) {
  await writeFile(
    new URL(`${name}.json`, directory),
    JSON.stringify(data) + "\n",
  );
}
await writeFile(
  new URL("../src/icons/loaders.ts", import.meta.url),
  `// Generated by scripts/generate-icons.mjs. Do not edit.\nexport const loaders = [\n${groups.map((_, index) => `  () => import("./data/${index}.json"),`).join("\n")}\n];\n`,
);
await writeFile(
  new URL("../src/IconType.ts", import.meta.url),
  `// Generated by scripts/generate-icons.mjs. Do not edit.\nexport type IconType =\n${names.map((name) => `  | "${name}"`).join("\n")};\n`,
);
