import { readFile, writeFile } from "node:fs/promises";

const collection = JSON.parse(
  await readFile("node_modules/@iconify-json/lucide/icons.json", "utf8"),
);
const names = [
  ...Object.keys(collection.icons),
  ...Object.keys(collection.aliases ?? {}),
].sort();
const members = names.map((name) => `  | "${name}"`).join("\n");
const content = `// Generated by scripts/generate-icon-types.mjs. Do not edit.\nexport type IconType =\n${members};\n`;

await writeFile("src/IconType.ts", content);
